/// The app's spacing scale, in logical pixels.
abstract final class Spacing {
  /// The smallest gap.
  static const double extraSmall = 2;

  /// A small gap.
  static const double small = 4;

  /// A gap between small and normal.
  static const double semiSmall = 6;

  /// The default gap.
  static const double normal = 10;

  /// A gap between normal and big.
  static const double semiBig = 15;

  /// A big gap.
  static const double big = 25;

  /// The largest gap.
  static const double extraBig = 50;
}
