#!/usr/bin/env bash
# Port mokuro-reader's OCR line layout to assets/manga-reader/mokuro-layout.js.
#
# The manga reader page lays each OCR line over its print with
# mokuro-reader's geometry: line-coords-layout.ts, line-grid.ts and
# glyph-insets.ts, which are pure functions. This bundles those three files,
# unchanged, into one ES module, with esbuild stripping the types. The only
# substitution is fonts-ready.ts, which depends on Svelte and mokuro-reader's
# web fonts: the reader page uses system fonts, so its font epoch never
# changes.
#
# Usage: tool/port_mokuro_layout.sh [--any-ref] <mokuro-reader checkout>
#
# The port is pinned to the commit below; --any-ref ports another one (then
# update PINNED_REF).
set -euo pipefail

PINNED_REF=bfaeb482
ESBUILD=esbuild@0.24.2

any_ref=false
if [[ ${1:-} == --any-ref ]]; then
  any_ref=true
  shift
fi
if [[ $# -ne 1 ]]; then
  echo "usage: $0 [--any-ref] <mokuro-reader checkout>" >&2
  exit 2
fi

checkout=$(cd "$1" && pwd)
repo=$(cd "$(dirname "$0")/.." && pwd)
ref=$(git -C "$checkout" rev-parse --short=8 HEAD)
if [[ $ref != "$PINNED_REF" && $any_ref == false ]]; then
  echo "$checkout is at $ref, not $PINNED_REF (use --any-ref to port it)" >&2
  exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

src=$checkout/src/lib/reader
cp "$src/line-coords-layout.ts" "$src/line-grid.ts" "$src/glyph-insets.ts" "$work/"
cat > "$work/fonts-ready.ts" <<'EOF'
// Stand-in for mokuro-reader's fonts-ready.ts: system fonts only.
export function currentFontLoadEpoch(): number {
  return 0;
}
EOF
cat > "$work/entry.ts" <<'EOF'
export {
  createCanvasMeasurer,
  getDefaultMeasurer,
  layoutLines,
  processLine
} from './line-coords-layout';
export { lineTransform } from './line-grid';
EOF

out=$repo/assets/manga-reader/mokuro-layout.js
(cd "$work" && pnpm dlx "$ESBUILD" entry.ts --bundle --format=esm \
  --log-level=warning --outfile=bundle.js)

{
  cat <<EOF
// Generated by tool/port_mokuro_layout.sh: do not edit.
//
// mokuro-reader's OCR line layout, from https://github.com/Gnathonic/mokuro-reader
// at $ref: src/lib/reader/line-coords-layout.ts, line-grid.ts and
// glyph-insets.ts, with their types stripped. fonts-ready.ts is replaced by
// a constant font epoch.
//
// Copyright the mokuro-reader authors. Licensed under the GNU General Public
// License, version 3 (see LICENSE in that repository), like this app.

EOF
  cat "$work/bundle.js"
} > "$out"

echo "wrote $out from $ref"
